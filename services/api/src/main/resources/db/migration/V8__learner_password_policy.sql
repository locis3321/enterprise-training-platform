-- V8：首次登录强制改密
--
-- 背景（代码审查 P2-6）：
--   初始密码规则是 anzhi + 手机号后 6 位，完全由手机号派生——
--   知道手机号即知道初始密码，属于可推导的弱口令。
--   改密入口与登录限流已具备，但没有「必须改」的约束，弱口令可长期存在。
--
-- 方案：用 must_change_password 标记驱动强制改密。
--   1. 账号创建（导入/手工建员工）时置 1；
--   2. 管理端重置密码后置回 1；
--   3. 学员自行改密成功后清 0；
--   4. AuthFilter 对「标记为 1 的学员」只放行改密与档案接口，其余一律 403。
--
-- 为什么在拦截器而不是各接口内部校验：
--   逐个接口判容易漏（新增接口忘了判就绕过了）。集中在一处，默认拒绝，
--   新增接口天然受保护。
--
-- 存量数据：已有账号无法判断其当前密码是否为初始密码（BCrypt 不可逆），
--   一律置 0（不打扰已有学员），只有新导入/重置的账号才强制改密。
-- ============================================================================

ALTER TABLE learner_account
    ADD COLUMN must_change_password TINYINT NOT NULL DEFAULT 0
        COMMENT '1=需强制改密（初始密码或管理端重置后置位，改密后清 0）';
