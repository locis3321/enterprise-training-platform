-- ============================================================================
-- V6：视频资源真实时长
--
-- 背景（2026-11-10 决策，用户要求）：
--   原设计把「章节时长」放在 course_section.duration_seconds，由管理员手填；
--   但管理端从未提供填写入口，导致通过界面建的章节时长恒为 NULL，
--   这些章节永远判不了完成，也无法自动修复。
--
-- 修订：时长是视频文件的内在属性，应由播放器读取后上报，不由人填。
--   1. 新增 course_resource.duration_seconds：视频真实时长（秒），
--      客户端首次播放时通过心跳上报，服务端「首次写入者胜」，之后不再覆盖。
--   2. 章节应看时长 = 该章节全部 VIDEO 资源时长之和（与既有「章节时长=全视频总时长」语义一致）。
--   3. course_section.duration_seconds 不再参与完成判定，保留列以兼容历史数据，
--      后续如确认无用可另行迁移删除（本轮不删，避免不可逆操作）。
--
-- 为什么时长放资源而不是章节：
--   同一视频可能被多个版本/章节复用（course_resource 是共享实体），
--   时长是文件属性，与「被绑到哪个章节」无关；放章节会导致重复录入与不一致。
-- ============================================================================

ALTER TABLE course_resource
    ADD COLUMN duration_seconds INT DEFAULT NULL
        COMMENT '视频真实时长（秒），由播放器上报；非视频为 NULL';

-- 回填：无。历史视频的真实时长只能由下一次播放上报，
-- 本迁移不猜测任何数值（猜测会直接污染完成判定）。
